class IndustryInputsTests(unittest.TestCase):
    def test_book_to_market_switches_in_july_and_drops_non_positive(self):
        months = ["202505", "202506", "202507", "202508"]
        ret = pd.DataFrame({"A": [1.0, 2.0, 3.0, 4.0]}, index=months)
        size = pd.DataFrame({"A": [10.0] * 4}, index=months)
        nf = pd.DataFrame({"A": [2.0] * 4}, index=months)
        bm = pd.DataFrame({"A": [0.5, -1.0]}, index=[2024, 2025])
        r, cap, b = pc.industry_inputs(ret, size, nf, bm)
        self.assertEqual(list(r["A"]), [0.01, 0.02, 0.03, 0.04])
        self.assertEqual(list(cap["A"]), [20.0] * 4)
        self.assertEqual(list(b["A"].iloc[:2]), [0.5, 0.5])   # Jan–Jun 2025 use June 2024
        self.assertTrue(b["A"].iloc[2:].isna().all())         # July on uses 2025, which is <= 0

    def test_relative_log_share_of_a_two_industry_market(self):
        idx = pd.PeriodIndex(["2026-01", "2026-02"], freq="M")
        ret = pd.DataFrame({"A": [0.10, 0.0], "B": [0.0, 0.0]}, index=idx)
        cap = pd.DataFrame({"A": [1.0, 1.0], "B": [1.0, 1.0]}, index=idx)
        rel = pc.relative_log_share(ret, cap)
        self.assertAlmostEqual(rel.loc[idx[0], "A"], math.log(1.10) - math.log(1.05))
        self.assertAlmostEqual(rel.loc[idx[0], "B"], -math.log(1.05))
        self.assertAlmostEqual(pc.wind(rel, 1).loc[idx[1], "A"], 0.0)


class PeerTests(unittest.TestCase):
    def peers(self):
        return pd.DataFrame({"ticker": ["X", "P1", "P2", "P3", "Q1"], "code": ["Softw"] * 4 + ["Banks"],
                             "capA": [10.0, 100.0, 100.0, 100.0, 50.0], "capB": [20.0, 110.0, 110.0, 110.0, 50.0]})

    def test_relative_wind_excludes_the_stock_itself(self):
        w, n = pc.relative_wind("X", "Softw", 1.0, 2.0, self.peers())
        self.assertEqual(n, 3)
        self.assertAlmostEqual(w, math.log(2.0) - math.log(1.1))

    def test_too_few_peers_or_a_missing_price_gives_no_wind(self):
        w, n = pc.relative_wind("Z", "Banks", 1.0, 2.0, self.peers())
        self.assertTrue(math.isnan(w))
        self.assertEqual(n, 1)
        self.assertTrue(math.isnan(pc.relative_wind("X", "Softw", np.nan, 2.0, self.peers())[0]))
        self.assertTrue(math.isnan(pc.relative_wind("X", "Softw", 0.0, 2.0, self.peers())[0]))

    def test_peer_table_keeps_one_share_class_and_drops_the_unclassified(self):
        cons = pd.DataFrame({
            "ticker": ["GOOGL", "GOOG", "MSFT", "ZZZ"],
            "name": ["Alphabet Inc. (Class A)", "Alphabet Inc. (Class C)", "Microsoft", "Mystery Co"],
            "yahoo": ["GOOGL", "GOOG", "MSFT", "ZZZ"], "shares": [10.0, 10.0, 5.0, 1.0]})
        closes = {"GOOGL": 2.0, "GOOG": 2.0, "MSFT": 4.0, "ZZZ": 1.0}
        t = pc.peer_table(cons, closes, closes, closes, {"GOOGL": "Softw", "GOOG": "Softw", "MSFT": "Softw"})
        self.assertEqual(list(t["ticker"]), ["GOOGL", "MSFT"])
        self.assertEqual(list(t["capA"]), [20.0, 20.0])


def _holding(**kw):
    h = {"value": 10_000.0, "weight": 0.05, "ind_weight": 0.05, "code": "Softw",
         "sw": np.nan, "sw_peers": 0, "sw_pct": np.nan}
    h.update(kw)
    return h


def _row(label, rank=10):
    return {"label": label, "industry": "Software", "rank": rank, "wind12": -0.12}


def _lots(*rows):
    return pd.DataFrame([{"value": v, "cost": c, "acquired": pd.Timestamp(a) if a else pd.NaT}
                         for v, c, a in rows])


class DecideTests(unittest.TestCase):
    TODAY = date(2026, 11, 17)
    P = pc.CheckParams()

    def decide(self, h, lots, row):
        return pc.decide(h, lots, row, 49, self.P, today=self.TODAY, sell_edge=-0.018)

    def test_unclassified_is_review(self):
        action, reasons, tax = self.decide(_holding(code=None), _lots((1, 1, "2020-01-01")), None)
        self.assertEqual((action, tax), ("Review", ""))
        self.assertIn("Could not match", reasons[0])

    def test_sell_waits_when_short_term_lots_are_close_to_long_term(self):
        # Bought 2025-12-01: long-term on 2026-12-02, 15 days away (<= 120).
        action, reasons, tax = self.decide(_holding(), _lots((10_000.0, 6_000.0, "2025-12-01")), _row("Sell"))
        self.assertEqual(action, "Sell after Dec 02, 2026")
        self.assertIn("Waiting 15 days until they turn long-term saves about $680 in tax", reasons[2])
        self.assertEqual(tax, "Selling now realizes $0 long-term and $4,000 short-term gain/loss; estimated tax $1,280.")

    def test_sell_now_when_the_wait_is_long_and_the_saving_small(self):
        # Long-term only on 2027-10-02 (319 days) and a $100 gain: waiting isn't worth it.
        action, _, _ = self.decide(_holding(), _lots((10_000.0, 9_900.0, "2026-10-01")), _row("Sell"))
        self.assertEqual(action, "Sell")

    def test_a_loss_is_flagged_for_harvesting(self):
        _, _, tax = self.decide(_holding(), _lots((8_000.0, 10_000.0, "2020-01-01")), _row("Sell"))
        self.assertTrue(tax.startswith("Selling now realizes −$2,000 long-term and $0 short-term"))
        self.assertIn("wash-sale rule", tax)

    def test_no_tax_note_without_a_cost_or_date_on_every_lot(self):
        lots = _lots((5_000.0, 4_000.0, "2020-01-01"), (5_000.0, None, "2021-01-01"))
        action, _, tax = self.decide(_holding(), lots, _row("Sell"))
        self.assertEqual((action, tax), ("Sell", ""))

    def test_buy_zone_respects_position_and_industry_caps(self):
        lots = _lots((1, 1, "2020-01-01"))
        self.assertEqual(self.decide(_holding(), lots, _row("Buy zone"))[0], "Buy / add")
        action, reasons, _ = self.decide(_holding(weight=0.12), lots, _row("Buy zone"))
        self.assertEqual(action, "Hold (at size limit)")
        self.assertIn("at or above the 10% position limit", reasons[1])
        action, reasons, _ = self.decide(_holding(ind_weight=0.30), lots, _row("Buy zone"))
        self.assertEqual(action, "Hold (at size limit)")
        self.assertIn("(limit 25%)", reasons[1])

    def test_watch_and_hold_and_the_large_position_note(self):
        lots = _lots((1, 1, "2020-01-01"))
        self.assertEqual(self.decide(_holding(), lots, _row("Watch"))[0], "Hold, on watch")
        action, reasons, _ = self.decide(_holding(weight=0.16), lots, _row("Hold"))
        self.assertEqual(action, "Hold")
        self.assertIn("Large position: 16.0%", reasons[-2])
        self.assertIn("Too few S&P 500 peers", reasons[-1])

    def test_stock_vs_peers_reason(self):
        h = _holding(sw=math.log(1.25), sw_peers=7, sw_pct=0.85)
        reasons = self.decide(h, _lots((1, 1, "2020-01-01")), _row("Hold"))[1]
        self.assertIn("Against its 7 S&P 500 industry peers, the stock is +25% over 12 months", reasons[-1])
        self.assertIn("in the top 20%", reasons[-1])


class CheckPortfolioTests(unittest.TestCase):
    def test_lots_roll_up_and_unclassified_holdings_sort_as_review(self):
        industries = pd.DataFrame([
            {"code": "Softw", "industry": "Software", "label": "Hold", "pct": 0.6, "pct_prev": 0.6,
             "wind12": 0.0, "wind60": 0.0, "bm": 0.2, "rank": 20.0},
            {"code": "Oil", "industry": "Oil & Gas", "label": "Buy zone", "pct": 0.9, "pct_prev": 0.9,
             "wind12": 0.1, "wind60": 0.0, "bm": 0.5, "rank": 3.0}])
        peers = pd.DataFrame({"ticker": ["XOM", "CVX"], "name": ["Exxon", "Chevron"], "code": ["Oil", "Oil"],
                              "shares": [1.0, 1.0], "capA": [1.0, 1.0], "capB": [1.0, 1.0], "cap": [200.0, 100.0]})
        lots = [{"ticker": "msft", "shares": 10, "price": 100.0, "cost": 500.0, "acquired": "2020-01-01"},
                {"ticker": "MSFT", "shares": 10, "price": 100.0, "cost": None, "acquired": None},
                {"ticker": "ZZZ", "shares": 5, "price": 20.0}]
        out = pc.check_portfolio(lots, industries, peers, {"MSFT": "Softw", "ZZZ": None}, {},
                                 today=date(2026, 11, 17), sell_edge=-0.018)
        self.assertEqual(out["total_value"], 2_100.0)
        self.assertEqual([(h["ticker"], h["action"]) for h in out["holdings"]], [("ZZZ", "Review"), ("MSFT", "Hold")])
        msft = out["holdings"][1]
        self.assertEqual((msft["shares"], msft["cost"]), (20.0, None))   # a lot without cost → no total cost
        self.assertIn("Software ranks 20 of 2 industries", msft["reasons"][0])
        self.assertEqual([i["industry"] for i in out["ideas"]], ["Oil & Gas"])
        self.assertEqual([e["ticker"] for e in out["ideas"][0]["examples"]], ["XOM", "CVX"])
        json.dumps(out, allow_nan=False)

    def test_action_order(self):
        actions = ["Buy / add", "Hold", "Sell after Jan 01, 2027", "Review", "Sell", "Hold, on watch",
                   "Hold (at size limit)"]
        self.assertEqual(sorted(actions, key=pc.action_sort_key),
                         ["Sell", "Sell after Jan 01, 2027", "Review", "Hold, on watch", "Hold",
                          "Hold (at size limit)", "Buy / add"])


