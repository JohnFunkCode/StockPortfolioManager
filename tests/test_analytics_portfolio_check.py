"""Unit tests for quantcore.analytics.portfolio_check — industry wind labels and decisions.

The parity tests replay a frozen run of the Market Casting prototype on its made-up
sample portfolio (tests/fixtures/portfolio_check/parity.json, regenerated by
make_fixture.py there) and require the same actions, reasons, tax notes and ideas.
"""

import json
import math
import unittest
from datetime import date
from pathlib import Path

import numpy as np
import pandas as pd

from quantcore.analytics import portfolio_check as pc

FIXTURE = Path(__file__).resolve().parent / "fixtures" / "portfolio_check" / "parity.json"


def _load_fixture() -> dict:
    return json.loads(FIXTURE.read_text(encoding="utf-8"))


def _frame(block: dict) -> pd.DataFrame:
    return pd.DataFrame(block["data"], index=block["index"], columns=block["columns"], dtype=float)


def _ideas_text(idea: dict) -> str:
    """The prototype's formatting of an idea's examples, from the structured output."""
    parts = [f"{e['ticker']} ({e['name']}; {e['vs_peers_12m']:+.0%} vs peers)" if e["vs_peers_12m"] is not None
             else f"{e['ticker']} ({e['name']})" for e in idea["examples"]]
    return ", ".join(parts) or "No S&P 500 members in this industry"


class ParityTests(unittest.TestCase):
    """The prototype's own results on its sample portfolio, reproduced."""

    @classmethod
    def setUpClass(cls):
        cls.fx = _load_fixture()
        fx = cls.fx
        cls.result = pc.check_portfolio(
            fx["lots"], pd.DataFrame(fx["industries"]), pd.DataFrame(fx["peers"]), fx["codes"],
            {t: tuple(v) for t, v in fx["window_prices"].items()},
            today=date.fromisoformat(fx["today"]), sell_edge=fx["sell_edge"],
        )

    def test_holdings_in_the_same_order_with_the_same_actions(self):
        got = [(h["ticker"], h["action"]) for h in self.result["holdings"]]
        want = [(h["ticker"], h["action"]) for h in self.fx["expected"]["holdings"]]
        self.assertEqual(got, want)

    def test_same_reasons_and_tax_notes_word_for_word(self):
        want = {h["ticker"]: h for h in self.fx["expected"]["holdings"]}
        for h in self.result["holdings"]:
            with self.subTest(ticker=h["ticker"]):
                self.assertEqual(h["reasons"], want[h["ticker"]]["reasons"])
                self.assertEqual(h["tax_note"], want[h["ticker"]]["tax"])

    def test_the_sample_exercises_tax_notes_and_several_actions(self):
        # Guards the fixture itself: a regeneration that lost the tax notes or
        # collapsed to one action would make the parity tests above toothless.
        actions = {h["action"] for h in self.fx["expected"]["holdings"]}
        self.assertTrue({"Sell", "Hold, on watch", "Buy / add", "Hold (at size limit)"} <= actions)
        self.assertTrue(any(h["tax"] for h in self.fx["expected"]["holdings"]))

    def test_same_numbers(self):
        self.assertAlmostEqual(self.result["total_value"], self.fx["expected"]["total_value"], places=6)
        want = {h["ticker"]: h for h in self.fx["expected"]["holdings"]}
        for h in self.result["holdings"]:
            w = want[h["ticker"]]
            with self.subTest(ticker=h["ticker"]):
                self.assertAlmostEqual(h["weight"], w["weight"], places=12)
                self.assertAlmostEqual(h["industry_weight"], w["ind_weight"], places=12)
                self.assertEqual(h["industry_label"], w["label"])
                self.assertEqual(h["industry_rank"], w["ind_rank"])
                self.assertEqual(h["peer_count"], w["sw_peers"])
                if w["sw"] is None:
                    self.assertIsNone(h["vs_peers_12m"])
                else:
                    self.assertAlmostEqual(h["vs_peers_12m"], math.expm1(w["sw"]), places=12)
                    self.assertAlmostEqual(h["vs_peers_percentile"], w["sw_pct"], places=12)

    def test_same_ideas(self):
        got = [(i["industry"], i["rank"], _ideas_text(i)) for i in self.result["ideas"]]
        want = [(i["industry"], i["rank"], i["examples"]) for i in self.fx["expected"]["ideas"]]
        self.assertEqual(got, want)
        for g, w in zip(self.result["ideas"], self.fx["expected"]["ideas"]):
            self.assertAlmostEqual(g["wind12"], w["wind12"], places=12)

    def test_output_is_json_ready(self):
        json.dumps(self.result, allow_nan=False)  # raises on a NaN or a numpy scalar


class IndustryStateParityTests(unittest.TestCase):
    """The industry state recomputed from the raw FF49 tail matches the prototype's
    full-history run: winds are differences of a cumulative series, so a truncated
    history gives the same answer."""

    def test_recomputed_from_raw_tables(self):
        fx = _load_fixture()
        ff = fx["ff49"]
        ret, cap, bm = pc.industry_inputs(_frame(ff["ret"]), _frame(ff["size"]), _frame(ff["nfirms"]), _frame(ff["bm"]))
        ind, asof = pc.industry_state(ret, cap, bm)
        self.assertEqual(asof, fx["industry_asof"])
        want = pd.DataFrame(fx["industries"])
        self.assertEqual(list(ind["code"]), list(want["code"]))
        self.assertEqual(list(ind["label"]), list(want["label"]))
        self.assertEqual(list(ind["rank"]), [int(r) for r in want["rank"]])
        for col in ("pct", "pct_prev", "wind12", "wind60", "bm"):
            np.testing.assert_allclose(ind[col].to_numpy(float), want[col].to_numpy(float),
                                       rtol=1e-9, atol=1e-12, equal_nan=True, err_msg=col)


